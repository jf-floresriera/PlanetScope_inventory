def construir_huellas(anio=HUELLAS_ANIO, forzar=False):
    ruta = os.path.join(CARPETAS['tablas'], f'HUELLAS_{anio}_POR_SENSOR.parquet')
    if os.path.exists(ruta) and not forzar:
        print('⚡ Huellas cargadas desde Drive')
        return pd.read_parquet(ruta)
    filas = []
    # Sentinel-2 y Landsat: una huella por tile / path-row (con el número de escenas del año)
    for sitio, bbox in AOIS_BBOX.items():
        for col_id, etiqueta in COLECCIONES_OPT.items():
            try:
                items = _cat().search(collections=[col_id], bbox=bbox,
                                      datetime=f'{anio}-01-01/{anio}-12-31').item_collection()
            except Exception as e:
                print(f'Aviso {etiqueta} {sitio}: {e}')
                continue
            grupos = {}
            for it in items:
                p = it.properties
                if col_id == 'landsat-c2-l2' and p.get('platform') not in ('landsat-8', 'landsat-9'):
                    continue
                clave = p.get('s2:mgrs_tile') or f"{p.get('landsat:wrs_path')}/{p.get('landsat:wrs_row')}"
                grupos.setdefault(clave, []).append(it)
            for clave, its in grupos.items():
                filas.append({'sitio': sitio, 'sensor': etiqueta, 'detalle': clave, 'n_escenas': len(its),
                              'fecha': '', 'wkt': shape(its[0].geometry).wkt})
    # EMIT: una huella por escena
    for sitio, bbox in AOIS_BBOX.items():
        try:
            res = earthaccess.search_data(short_name='EMITL2ARFL', bounding_box=bbox,
                                          temporal=(f'{anio}-01-01', f'{anio}-12-31'))
        except Exception as e:
            print(f'Aviso EMIT {sitio}: {e}')
            continue
        for g in res:
            umm = g['umm']
            geom = _geom_umm(umm)
            if geom is None or geom.is_empty:
                continue
            f = (umm.get('TemporalExtent', {}).get('RangeDateTime', {}).get('BeginningDateTime', '') or '')[:10]
            filas.append({'sitio': sitio, 'sensor': 'EMIT', 'detalle': umm.get('GranuleUR'),
                          'n_escenas': 1, 'fecha': f, 'wkt': geom.wkt})
    # EnMAP: escenas que cubren el AOI (ya calculadas en DF_EN)
    if 'DF_EN' in globals() and len(DF_EN):
        for _, r in DF_EN[(DF_EN['anio'] == anio) & (DF_EN['toca_aoi'])].iterrows():
            filas.append({'sitio': r['sitio'], 'sensor': 'EnMAP L2A', 'detalle': r['id_escena'],
                          'n_escenas': 1, 'fecha': r['fecha'], 'wkt': r['huella_wkt']})
    df = pd.DataFrame(filas)
    if not df.empty:
        df.to_parquet(ruta, index=False)
        df.drop(columns=['wkt']).to_csv(ruta.replace('.parquet', '.csv'), index=False)
    print(f'✅ {len(df)} huellas guardadas en Drive')
    return df

def mapa_huellas_sensores(df, delta=0.9, anio=HUELLAS_ANIO):
    fig, axes = plt.subplots(2, 2, figsize=(14, 13))
    for ax, (s, (lat, lon)) in zip(axes.ravel(), SITIOS.items()):
        ss = df[df['sitio'] == s]
        for _, r in ss.iterrows():
            est = ESTILO_SENSOR.get(r['sensor'], dict(color='k', ls='-', lw=1, fill=False))
            g = _wkt.loads(r['wkt'])
            for poly in (g.geoms if hasattr(g, 'geoms') else [g]):
                if not hasattr(poly, 'exterior'):
                    continue
                x, y = poly.exterior.xy
                if est['fill']:
                    ax.fill(x, y, color=est['color'], alpha=0.18, zorder=3)
                ax.plot(x, y, color=est['color'], ls=est['ls'], lw=est['lw'], zorder=3)
            if r['sensor'] in ('EMIT', 'EnMAP L2A') and r['fecha']:
                c = g.representative_point()
                ax.annotate(r['fecha'][5:], (c.x, c.y), fontsize=7, ha='center', color=est['color'], zorder=5)
        handles = []
        for sen, est in ESTILO_SENSOR.items():
            sub = ss[ss['sensor'] == sen]
            if sub.empty:
                continue
            if sen in ('Sentinel-2 L2A', 'Landsat 8/9 C2 L2'):
                txt = f"{sen}: {len(sub)} tile(s), {int(sub['n_escenas'].sum())} escenas"
            else:
                txt = f'{sen}: {len(sub)} escena(s)'
            handles.append(Line2D([0], [0], color=est['color'], ls=est['ls'], lw=2, label=txt))
        handles.append(Line2D([0], [0], marker='+', color='red', linestyle='', markersize=12, label='Sitio (centro del AOI)'))
        ax.plot(lon, lat, marker='+', color='red', markersize=16, mew=2, zorder=6)
        ax.set_xlim(lon - delta, lon + delta)
        ax.set_ylim(lat - delta, lat + delta)
        ax.set_aspect(1 / math.cos(math.radians(lat)))
        ax.set_title(f'{s}', fontsize=12, fontweight='bold')
        ax.legend(handles=handles, fontsize=8, loc='lower left')
        ax.grid(alpha=0.3)
    fig.suptitle(f'Huellas aproximadas de las escenas {anio} por sensor (solo las que incluyen el AOI)', fontsize=14)
    plt.tight_layout(rect=(0, 0, 1, 0.97))
    plt.savefig(os.path.join(CARPETAS['figuras'], f'mapa_huellas_sensores_{anio}.png'), dpi=200, bbox_inches='tight')
    plt.show()

