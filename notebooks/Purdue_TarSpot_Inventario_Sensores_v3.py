def _geom_umm(umm):
    try:
        g = umm['SpatialExtent']['HorizontalSpatialDomain']['Geometry']
    except KeyError:
        return None
    geoms = []
    for gp in g.get('GPolygons', []):
        pts = [(p['Longitude'], p['Latitude']) for p in gp['Boundary']['Points']]
        if len(pts) >= 4:
            geoms.append(Polygon(pts))
    for br in g.get('BoundingRectangles', []):
        geoms.append(box(br['WestBoundingCoordinate'], br['SouthBoundingCoordinate'],
                         br['EastBoundingCoordinate'], br['NorthBoundingCoordinate']))
    if not geoms:
        return None
    u = unary_union([x if x.is_valid else x.buffer(0) for x in geoms])
    return u

