def _idx(wl, w):
    return int(np.nanargmin(np.abs(wl - w)))

def _banda(esc, w):
    return esc['refl'][_idx(esc['wl'], w)]

def _estirar(img, p=(2, 98)):
    out = np.zeros_like(img)
    for i in range(img.shape[-1]):
        lo, hi = np.nanpercentile(img[..., i], p)
        out[..., i] = np.clip((img[..., i] - lo) / (hi - lo + 1e-9), 0, 1)
    return np.nan_to_num(out)

def _compuesto(esc, ws):
    return _estirar(np.dstack([_banda(esc, w) for w in ws]))

def indices_espectrales(esc):
    B = lambda w: _banda(esc, w)
    e = 1e-9
    return {'NDVI (860/650 nm)': (B(860) - B(650)) / (B(860) + B(650) + e),
            'NDRE (790/720 nm)': (B(790) - B(720)) / (B(790) + B(720) + e),
            'NDMI (860/1610 nm)': (B(860) - B(1610)) / (B(860) + B(1610) + e),
            'PSRI (680/500/750 nm)': (B(680) - B(500)) / (B(750) + e)}

def _puntos_muestra(ndvi, aoi):
    """Píxeles del AOI con NDVI alto (p95), medio (p50) y bajo (p5)."""
    sub = ndvi[aoi]
    ok = np.argwhere(np.isfinite(sub))
    vals = sub[np.isfinite(sub)]
    orden = np.argsort(vals)
    puntos = {}
    for nombre, p in (('A · NDVI alto (p95)', 0.95), ('B · NDVI medio (p50)', 0.50), ('C · NDVI bajo (p5)', 0.05)):
        rr, cc = ok[orden[int(p * (len(orden) - 1))]]
        puntos[nombre] = (rr + aoi[0].start, cc + aoi[1].start)
    return puntos

