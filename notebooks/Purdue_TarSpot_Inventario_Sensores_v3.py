def descargar_enmap(url, carpeta=CARPETAS['enmap']):
    if not url:
        print('⚠️ URL vacía'); return None
    nombre = url.split('?')[0].rstrip('/').split('/')[-1]
    destino = os.path.join(carpeta, nombre)
    if os.path.exists(destino) and os.path.getsize(destino) > 1024 * 1024:
        print('⚡ Ya existe en Drive:', destino); return destino
    u, p = _cred_dlr()
    parte = destino + '.part'
    pos = os.path.getsize(parte) if os.path.exists(parte) else 0
    headers = {'Range': f'bytes={pos}-'} if pos else {}
    with SesionDLR() as s:
        s.auth = (u, p)
        r = s.get(url, headers=headers, stream=True, timeout=120)
        if r.status_code in (401, 403):
            raise PermissionError(f'HTTP {r.status_code}: usuario/clave incorrectos o la cuenta no tiene acceso a datos EnMAP.')
        if 'text/html' in r.headers.get('Content-Type', ''):
            raise RuntimeError(f'El servidor devolvió una página HTML (¿login?) en {r.url}: {r.text[:200]!r}')
        r.raise_for_status()
        reanuda = r.status_code == 206
        total = int(r.headers.get('Content-Length', 0)) + (pos if reanuda else 0)
        with open(parte, 'ab' if reanuda else 'wb') as f, \
             tqdm(total=total, initial=pos if reanuda else 0, unit='B', unit_scale=True, desc=nombre) as bar:
            for chunk in r.iter_content(1024 * 1024):
                if chunk:
                    f.write(chunk); bar.update(len(chunk))
    os.replace(parte, destino)
    print('✅ Guardado en Drive:', destino)
    return destino

