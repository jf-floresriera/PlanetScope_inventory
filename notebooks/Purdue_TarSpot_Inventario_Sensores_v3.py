def _wl_valida(wl, n):
    return (wl is not None and len(wl) == n and np.all(np.isfinite(wl)) and np.all(np.diff(wl) > 0)
            and 350 <= wl.min() and wl.max() <= 2600)

def _wl_desde_raster(src):
    wl = []
    for i in range(1, src.count + 1):
        v = None
        for k, val in src.tags(i).items():
            if 'wavelength' in k.lower() and 'fwhm' not in k.lower():
                try:
                    v = float(str(val).split()[0]); break
                except ValueError:
                    pass
        if v is None and src.descriptions[i - 1]:
            m = re.search(r'(\d{3,4}(?:\.\d+)?)\s*nm', src.descriptions[i - 1])
            if m:
                v = float(m.group(1))
        wl.append(np.nan if v is None else v)
    wl = np.array(wl, dtype='float')
    return wl if _wl_valida(wl, src.count) else None

def _wl_desde_xml(carpeta, n):
    for f in glob.glob(os.path.join(carpeta, '*METADATA*')):
        if not f.lower().endswith('.xml'):
            continue
        txt = open(f, encoding='utf-8', errors='ignore').read()
        vals = np.array([float(x) for x in re.findall(r'<wavelengthCenterOfBand>\s*([\d.]+)\s*</wavelengthCenterOfBand>', txt)])
        if _wl_valida(vals, n):
            return vals
        if len(vals):
            print(f'⚠️ El XML trae {len(vals)} longitudes de onda y el raster {n} bandas: no se pueden emparejar.')
    return None

def cargar_escena(ruta, sitio, contexto_m=CONTEXTO_M):
    fecha = re.search(r'_(\d{8})T', os.path.basename(ruta))
    fecha = pd.to_datetime(fecha.group(1)).strftime('%Y-%m-%d') if fecha else ''
    lat, lon = SITIOS[sitio]
    with rasterio.open(ruta) as src:
        l, b, r, t = transform_bounds('EPSG:4326', src.crs, *bbox_aoi(lat, lon, contexto_m))
        w = from_bounds(l, b, r, t, transform=src.transform)
        win = Window(int(round(w.col_off)), int(round(w.row_off)), int(round(w.width)), int(round(w.height)))
        arr = src.read(window=win).astype('float32')
        tr = src.window_transform(win)
        la, ba, ra, ta = transform_bounds('EPSG:4326', src.crs, *AOIS_BBOX[sitio])
        wl = _wl_desde_raster(src)
        if wl is None:
            wl = _wl_desde_xml(os.path.join(os.path.dirname(ruta), 'metadatos'), src.count)
        if wl is None:
            print('⚠️ No encontré las longitudes de onda. Etiquetas del raster:', list(src.tags().keys())[:12],
                  '| banda 1:', src.tags(1), '| descripción:', src.descriptions[0])
            raise ValueError('Faltan las longitudes de onda (corre antes la celda de metadatos).')
        nodata = src.nodata
    if nodata is not None:
        arr[arr == nodata] = np.nan
    arr[arr <= -9000] = np.nan
    refl = arr * ESCALA
    p99 = np.nanpercentile(refl, 99)
    print(f'{sitio} {fecha}: {refl.shape[0]} bandas, {refl.shape[1]}x{refl.shape[2]} px, '
          f'{wl.min():.0f}–{wl.max():.0f} nm, reflectancia p99 = {p99:.2f}'
          + ('  ⚠️ revisa la escala (esperado < 1)' if p99 > 1.5 else ''))
    r0, c0 = (int(np.ravel(v)[0]) for v in rowcol(tr, la, ta))
    r1, c1 = (int(np.ravel(v)[0]) for v in rowcol(tr, ra, ba))
    aoi = (slice(max(r0, 0), min(r1 + 1, refl.shape[1])), slice(max(c0, 0), min(c1 + 1, refl.shape[2])))
    return {'sitio': sitio, 'fecha': fecha, 'ruta': ruta, 'refl': refl, 'wl': wl, 'aoi': aoi}

