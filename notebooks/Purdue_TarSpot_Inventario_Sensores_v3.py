"""### 3.2 Previsualización aleatoria (recorte del AOI de 1500 m)

Lee solo la ventana del AOI desde los COG (no descarga escenas completas). Si falla, cae a la miniatura `rendered_preview` de la escena completa. Se indica el % de píxeles sin datos (escenas de borde).
"""

def _leer_ventana(href, bbox, px):
    with rasterio.open(href) as src:
        l, b, r, t = transform_bounds('EPSG:4326', src.crs, *bbox)
        win = from_bounds(l, b, r, t, transform=src.transform)
        return src.read(window=win, out_shape=(src.count, px, px), boundless=True,
                        fill_value=0, resampling=Resampling.bilinear)

def recorte_rgb(fila, px=300):
    it = next(_cat().search(collections=[fila['coleccion']], ids=[fila['id_escena']]).items())
    bbox = AOIS_BBOX[fila['sitio']]
    try:
        if fila['coleccion'] == 'sentinel-2-l2a':
            arr = _leer_ventana(it.assets['visual'].href, bbox, px)
            return np.transpose(arr, (1, 2, 0)).astype('uint8')
        canales = []
        for b in ('red', 'green', 'blue'):
            a = _leer_ventana(it.assets[b].href, bbox, px)[0].astype('float32')
            canales.append(np.where(a > 0, a * 0.0000275 - 0.2, 0))
        rgb = np.dstack(canales)
        return (np.clip(rgb / 0.25, 0, 1) ** (1 / 1.8) * 255).astype('uint8')
    except Exception as e:
        print(f'  ↪ recorte falló ({e}); uso miniatura completa')
        url = it.assets['rendered_preview'].href
        return np.array(Image.open(io.BytesIO(requests.get(url, timeout=60).content)).convert('RGB'))

def preview_aleatorio(df, n=6, sensor=None, sitio=None, anio=None, max_nube=30, semilla=SEMILLA, cols=3):
    sub = df.copy()
    if sensor: sub = sub[sub['sensor'].str.contains(sensor, case=False)]
    if sitio:  sub = sub[sub['sitio'] == sitio]
    if anio:   sub = sub[sub['anio'] == anio]
    if max_nube is not None: sub = sub[sub['nube_pct'].fillna(0) <= max_nube]
    if sub.empty:
        print('⚠️ Sin escenas con esos filtros'); return
    muestra = sub.sample(min(n, len(sub)), random_state=semilla).sort_values('fecha')
    filas = math.ceil(len(muestra) / cols)
    fig, axes = plt.subplots(filas, cols, figsize=(5 * cols, 5.2 * filas))
    axes = np.atleast_1d(axes).ravel()
    for ax, (_, r) in zip(axes, muestra.iterrows()):
        try:
            img = recorte_rgb(r)
            vacio = (img.sum(axis=2) == 0).mean() * 100
            ax.imshow(img)
            ax.set_title(f"{r['sensor']}\n{r['sitio']} · {r['fecha']} · nube {r['nube_pct']:.0f}% · sin datos {vacio:.0f}%", fontsize=9)
        except Exception as e:
            ax.text(0.5, 0.5, f'Error\n{str(e)[:80]}', ha='center', va='center')
        ax.axis('off')
    for ax in axes[len(muestra):]:
        ax.axis('off')
    plt.tight_layout(); plt.show()

