def descargar_hiperespectral(df, sensor_contiene='EMIT', sitio=None, min_solape_pct=50,
                             max_gb=20, solo_listar=True):
    sub = df[df['sensor'].str.contains(sensor_contiene, case=False)]
    if sitio:
        sub = sub[sub['sitio'] == sitio]
    sub = sub[sub['solape_aoi_pct'].fillna(0) >= min_solape_pct].drop_duplicates('id_escena')
    gb = sub['tam_mb'].fillna(0).sum() / 1024
    print(f'{len(sub)} escenas | ~{gb:.2f} GB')
    if solo_listar:
        display(sub[['sitio', 'fecha', 'id_escena', 'solape_aoi_pct', 'nube_pct', 'tam_mb']])
        return []
    if gb > max_gb:
        raise ValueError(f'Superaría max_gb={max_gb}. Filtra más o sube el límite.')
    rutas = []
    for _, r in sub.iterrows():
        destino = os.path.join(CARPETAS['nasa_hyp'], r['sitio'], r['short_name'], str(r['anio']))
        os.makedirs(destino, exist_ok=True)
        pendientes = [u for u in r['urls'] if not os.path.exists(os.path.join(destino, u.split('/')[-1]))]
        if pendientes:
            rutas += earthaccess.download(pendientes, local_path=destino)
    print('✅ Descarga terminada:', len(rutas), 'archivos nuevos')
    return rutas

