def _con_huecos(wl, y, salto=15):
    """Inserta NaN donde faltan bandas, para que la línea se corte y no una puntos lejanos."""
    i = np.where(np.diff(wl) > salto)[0] + 1
    return np.insert(np.asarray(wl, float), i, np.nan), np.insert(np.asarray(y, float), i, np.nan)

